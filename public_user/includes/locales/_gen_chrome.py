def mapping_for(code: str, keys: list[str], overlays: dict) -> dict[str, str]:
    en = {k: k for k in keys}
    if code in overlays:
        return {**en, **overlays[code]}
    src = aliases().get(code)
    if src and src in overlays:
        return {**en, **overlays[src]}
    return dict(en)


def main() -> None:
    from _ui_extra import EXTRA_KEYS, EXTRA_OVR

    keys = list(KEYS)
    seen = set(keys)
    for k in EXTRA_KEYS:
        if k not in seen:
            keys.append(k)
            seen.add(k)
    overlays = {code: dict(m) for code, m in OVR.items()}
    for code, extra in EXTRA_OVR.items():
        overlays.setdefault(code, {}).update(extra)

    codes = sorted(
        p.stem
        for p in ROOT.glob("*.php")
        if p.name[0] != "_" and p.stem not in {"_chrome"}
    )
    lines = ["<?php", "declare(strict_types=1);", "", "return ["]
    for code in codes:
        mapping = mapping_for(code, keys, overlays)
        lines.append(f"    '{php_escape(code)}' => [")
        for k in keys:
            lines.append(f"        '{php_escape(k)}' => '{php_escape(mapping[k])}',")
        lines.append("    ],")
    lines.append("];")
    lines.append("")
    out = ROOT / "_chrome.php"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out} locales={len(codes)} keys={len(keys)}")


if __name__ == "__main__":
    main()
